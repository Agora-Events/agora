/**
 * proofGenerator.test.ts — Issue #1186.
 *
 * ## The conformance vectors
 *
 * A proof is only useful if the Rust verifier accepts it, and nothing in CI
 * runs Rust and TypeScript in the same process. So the contract between the
 * two implementations is pinned by vectors instead: the hex strings in
 * `VECTORS` below were produced by the reference prover in
 * `server/src/utils/zkp_verifier.rs`, and `conformance_proof_is_valid` there
 * asserts the same proof verifies.
 *
 * Both provers are driven by the identical deterministic scalar stream
 * (`vectorRng`, mirroring `VectorRng` in the Rust `conformance` module), so
 * they must emit byte-identical proofs. If this file goes red, the two
 * implementations have diverged and real check-ins would fail at the gate.
 *
 * Regenerate with:
 * `cargo test -p agora-server zkp_conformance -- --ignored --nocapture`
 */

