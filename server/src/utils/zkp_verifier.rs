/// Verifies a ring Chaum–Pedersen proof.
///
/// Steps, in the order they are cheapest to reject at:
///
///  1. structural checks (version, ring length agreement, size bounds),
///  2. the anonymity set reproduces `ctx.merkle_root`,
///  3. the nullifier is a valid, non-identity point,
///  4. recompute every `(A_i, B_i)` from `(c_i, z_t,i, z_s,i)` and check that
///     the per-member challenges sum to the transcript challenge.
///
/// Step 4 dominates: two 3-term and 2-term multiscalar multiplications per
/// member, in variable time. Variable time is fine here — every input to it is
/// public (the proof and the ring); the secret witness never touches this path.
pub fn verify(
    proof: &RingProof,
    ctx: &VerificationContext<'_>,
) -> Result<VerifiedAttestation, ZkpError> {
    if proof.version != PROOF_VERSION {
        return Err(ZkpError::UnsupportedVersion(proof.version));
    }
    if proof.tier != ctx.tier {
        return Err(ZkpError::VerificationFailed);
    }
    check_ring_size(ctx)?;

    let n = ctx.ring.len();
    if proof.challenges.len() != n || proof.z_ticket.len() != n || proof.z_secret.len() != n {
        return Err(ZkpError::RingMismatch);
    }

    // The ring is only meaningful if it is *the* published set. Without this,
    // a malicious scanner could hand the verifier a one-element ring made of a
    // commitment it wants to test for, and learn which attendee is present.
    let leaves: Vec<[u8; 32]> = ctx.ring.iter().map(RingMember::leaf).collect();
    if merkle_root(&leaves) != ctx.merkle_root {
        return Err(ZkpError::RootMismatch);
    }

    let nullifier = proof
        .nullifier
        .decompress()
        .ok_or(ZkpError::NonCanonicalEncoding)?;
    if nullifier == RistrettoPoint::identity() {
        return Err(ZkpError::DegenerateNullifier);
    }

    let omega = nullifier_base(ctx.event_id, ctx.epoch);
    let omega_compressed = omega.compress();
    let g = generator_g();
    let h = generator_h();

    let mut hasher = base_transcript(ctx, proof.version, &omega_compressed, &proof.nullifier);
    let mut challenge_sum = Scalar::ZERO;

    for i in 0..n {
        let c_i = proof.challenges[i];
        let neg_c = -c_i;

        // A_i = z_t·G + z_s·H − c_i·C_i
        let a_i = RistrettoPoint::vartime_multiscalar_mul(
            [proof.z_ticket[i], proof.z_secret[i], neg_c],
            [g, h, ctx.ring[i].point],
        );
        // B_i = z_s·Ω − c_i·N
        let b_i =
            RistrettoPoint::vartime_multiscalar_mul([proof.z_secret[i], neg_c], [omega, nullifier]);

        absorb(&mut hasher, a_i.compress().as_bytes());
        absorb(&mut hasher, b_i.compress().as_bytes());
        challenge_sum += c_i;
    }

    if finalize_to_scalar(hasher) != challenge_sum {
        return Err(ZkpError::VerificationFailed);
    }

    Ok(VerifiedAttestation {
        nullifier: proof.nullifier,
        tier: ctx.tier,
        anonymity_set_size: n,
    })
}

// ── Prover ───────────────────────────────────────────────────────────────────

/// The secret the attendee's device holds for one ticket.
#[derive(Debug, Clone)]
pub struct Witness {
    /// Index of the attendee's own commitment inside the ring.
    pub index: usize,
    /// `t`, the ticket scalar.
    pub ticket: Scalar,
    /// `s`, the blinding scalar and nullifier key.
    pub secret: Scalar,
}

/// Randomness source for the prover.
///
/// Abstracted so tests can drive the prover deterministically; production
/// callers pass an OS-backed RNG.
pub trait ProverRng {
    /// Returns a uniformly random scalar.
    fn next_scalar(&mut self) -> Scalar;
}

/// [`ProverRng`] over any `rand::RngCore`.
pub struct RandProverRng<R>(pub R);

impl<R: rand::RngCore> ProverRng for RandProverRng<R> {
    fn next_scalar(&mut self) -> Scalar {
        let mut wide = [0u8; 64];
        self.0.fill_bytes(&mut wide);
        Scalar::from_bytes_mod_order_wide(&wide)
    }
}

/// Builds a ring Chaum–Pedersen proof.
///
/// This is the reference implementation of the protocol the mobile prover in
/// `apps/mobile/lib/zkp/proofGenerator.ts` reimplements in TypeScript. It is
/// the authority on the transcript layout, and it generates the cross-language
/// test vectors that pin the two implementations together.
///
/// It is also what issuer-side tooling and integration tests use. Real
/// attendee proofs are generated on-device, because `witness.secret` must
/// never reach the server.
pub fn prove<R: ProverRng>(
    witness: &Witness,
    ctx: &VerificationContext<'_>,
    rng: &mut R,
) -> Result<RingProof, ZkpError> {
    check_ring_size(ctx)?;
    let n = ctx.ring.len();
    if witness.index >= n {
        return Err(ZkpError::WitnessOutOfRange(witness.index));
    }
    if commit(witness.ticket, witness.secret) != ctx.ring[witness.index].point {
        return Err(ZkpError::WitnessMismatch);
    }

    let omega = nullifier_base(ctx.event_id, ctx.epoch);
    let omega_compressed = omega.compress();
    let nullifier = omega * witness.secret;
    let nullifier_compressed = nullifier.compress();
    let g = generator_g();
    let h = generator_h();

    let l = witness.index;

    // Simulate every member except the real one: pick the challenge and both
    // responses at random, then solve the verification equation *backwards*
    // for (A_i, B_i). A simulated transcript is distributed identically to an
    // honest one, which is exactly why the verifier cannot tell them apart —
    // this is the zero-knowledge property, not a shortcut around it.
    let mut challenges = vec![Scalar::ZERO; n];
    let mut z_ticket = vec![Scalar::ZERO; n];
    let mut z_secret = vec![Scalar::ZERO; n];
    let mut a_points = vec![RistrettoPoint::identity(); n];
    let mut b_points = vec![RistrettoPoint::identity(); n];

    for (i, member) in ctx.ring.iter().enumerate() {
        if i == l {
            continue;
        }
        let c_i = rng.next_scalar();
        let zt = rng.next_scalar();
        let zs = rng.next_scalar();
        challenges[i] = c_i;
        z_ticket[i] = zt;
        z_secret[i] = zs;
        a_points[i] = RistrettoPoint::vartime_multiscalar_mul([zt, zs, -c_i], [g, h, member.point]);
        b_points[i] = RistrettoPoint::vartime_multiscalar_mul([zs, -c_i], [omega, nullifier]);
    }

    // The real member commits honestly.
    let r_ticket = rng.next_scalar();
    let r_secret = rng.next_scalar();
    a_points[l] = RistrettoPoint::vartime_multiscalar_mul([r_ticket, r_secret], [g, h]);
    b_points[l] = omega * r_secret;

    // Fiat–Shamir over the whole ring of commitments.
    let mut hasher = base_transcript(ctx, PROOF_VERSION, &omega_compressed, &nullifier_compressed);
    for i in 0..n {
        absorb(&mut hasher, a_points[i].compress().as_bytes());
        absorb(&mut hasher, b_points[i].compress().as_bytes());
    }
    let challenge = finalize_to_scalar(hasher);

    // The one degree of freedom left: c_l is forced to make the sum come out
    // right, and only someone who knows (t, s) can then answer it.
    let simulated_sum: Scalar = challenges
        .iter()
        .enumerate()
        .filter(|(i, _)| *i != l)
        .map(|(_, c)| *c)
        .sum();
    let c_l = challenge - simulated_sum;
    challenges[l] = c_l;
    z_ticket[l] = r_ticket + c_l * witness.ticket;
    z_secret[l] = r_secret + c_l * witness.secret;

    Ok(RingProof {
        version: PROOF_VERSION,
        tier: ctx.tier,
        nullifier: nullifier_compressed,
        challenges,
        z_ticket,
        z_secret,
    })
}

// ── Pluggable backend ────────────────────────────────────────────────────────

/// The verification surface the check-in handler depends on.
///
/// The handler is written against this trait rather than against [`verify`]
/// directly, so a Groth16 backend can replace the sigma protocol later — once
/// there is a real trusted-setup ceremony to justify it — without the handler,
/// the nullifier store, or the wire API changing.
pub trait ProofSystem {
    /// Stable identifier recorded alongside spent nullifiers, so a future
    /// migration can tell which scheme produced a given row.
    fn scheme_id(&self) -> &'static str;

    /// Verifies an encoded proof against a context.
    fn verify_encoded(
        &self,
        proof_bytes: &[u8],
        ctx: &VerificationContext<'_>,
    ) -> Result<VerifiedAttestation, ZkpError>;
}

/// The ring Chaum–Pedersen backend described in this module.
#[derive(Debug, Clone, Copy, Default)]
pub struct RingChaumPedersen;

impl ProofSystem for RingChaumPedersen {
    fn scheme_id(&self) -> &'static str {
        "ring-cp-ristretto255-v1"
    }

    fn verify_encoded(
        &self,
        proof_bytes: &[u8],
        ctx: &VerificationContext<'_>,
    ) -> Result<VerifiedAttestation, ZkpError> {
        let proof = RingProof::from_bytes(proof_bytes)?;
        verify(&proof, ctx)
    }
}

